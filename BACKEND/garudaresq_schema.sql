-- GarudaResQ PostgreSQL schema
-- Run this script in Query Tool after selecting the garudaresq database.
-- PostgreSQL 14 or newer.

CREATE TABLE IF NOT EXISTS app_users (
    user_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    username VARCHAR(80) NOT NULL UNIQUE,
    full_name VARCHAR(120) NOT NULL,
    password_hash TEXT NOT NULL,
    role VARCHAR(20) NOT NULL CHECK (role IN ('citizen', 'ngo', 'shelter', 'admin')),
    assigned_shelter_id VARCHAR(40),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS victims (
    victim_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(120) NOT NULL,
    location_name VARCHAR(200) NOT NULL,
    latitude NUMERIC(9,6),
    longitude NUMERIC(9,6),
    people_affected INTEGER NOT NULL DEFAULT 1 CHECK (people_affected >= 0),
    injury_level SMALLINT CHECK (injury_level BETWEEN 1 AND 5),
    disaster_type VARCHAR(80),
    required_resource VARCHAR(150),
    contact_number VARCHAR(25),
    description TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS emergency_requests (
    request_id VARCHAR(40) PRIMARY KEY,
    victim_id BIGINT REFERENCES victims(victim_id) ON DELETE SET NULL,
    citizen_name VARCHAR(120) NOT NULL,
    location_name VARCHAR(200) NOT NULL,
    latitude NUMERIC(9,6),
    longitude NUMERIC(9,6),
    category VARCHAR(40) NOT NULL CHECK (category IN ('Flood', 'Landslide', 'Structural Damage', 'Medical')),
    priority VARCHAR(20) NOT NULL CHECK (priority IN ('critical', 'high', 'moderate', 'low')),
    priority_score SMALLINT CHECK (priority_score BETWEEN 0 AND 100),
    people_count INTEGER NOT NULL DEFAULT 1 CHECK (people_count > 0),
    description TEXT NOT NULL,
    contact_number VARCHAR(25) NOT NULL,
    request_status VARCHAR(20) NOT NULL DEFAULT 'pending'
        CHECK (request_status IN ('pending', 'dispatched', 'acquired', 'resolved')),
    acquired_by VARCHAR(120),
    reported_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS rescue_teams (
    team_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_name VARCHAR(120) NOT NULL,
    location VARCHAR(200) NOT NULL,
    is_available BOOLEAN NOT NULL DEFAULT TRUE,
    assigned_request_id VARCHAR(40) REFERENCES emergency_requests(request_id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS shelters (
    shelter_id VARCHAR(40) PRIMARY KEY,
    shelter_name VARCHAR(160) NOT NULL,
    location_area VARCHAR(200) NOT NULL,
    latitude NUMERIC(9,6) NOT NULL,
    longitude NUMERIC(9,6) NOT NULL,
    total_capacity INTEGER NOT NULL CHECK (total_capacity >= 0),
    current_occupancy INTEGER NOT NULL DEFAULT 0 CHECK (current_occupancy >= 0),
    contact_person VARCHAR(120),
    phone VARCHAR(25),
    status VARCHAR(20) NOT NULL DEFAULT 'operational'
        CHECK (status IN ('operational', 'high_occupancy', 'full')),
    last_updated TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (current_occupancy <= total_capacity)
);

ALTER TABLE app_users
    DROP CONSTRAINT IF EXISTS app_users_assigned_shelter_id_fkey;
ALTER TABLE app_users
    ADD CONSTRAINT app_users_assigned_shelter_id_fkey
    FOREIGN KEY (assigned_shelter_id) REFERENCES shelters(shelter_id) ON DELETE SET NULL;

CREATE TABLE IF NOT EXISTS shelter_resources (
    shelter_resource_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    shelter_id VARCHAR(40) NOT NULL REFERENCES shelters(shelter_id) ON DELETE CASCADE,
    resource_name VARCHAR(50) NOT NULL
        CHECK (resource_name IN ('foodPacks', 'waterLiters', 'medicalKits', 'generatorPower', 'blankets')),
    current_quantity NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (current_quantity >= 0),
    initial_quantity NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (initial_quantity >= 0),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (shelter_id, resource_name)
);

CREATE TABLE IF NOT EXISTS evacuee_logs (
    evacuee_id VARCHAR(40) PRIMARY KEY,
    shelter_id VARCHAR(40) NOT NULL REFERENCES shelters(shelter_id) ON DELETE RESTRICT,
    head_of_family VARCHAR(120) NOT NULL,
    people_count INTEGER NOT NULL CHECK (people_count > 0),
    origin_area VARCHAR(200) NOT NULL,
    checked_in_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    medical_needs TEXT,
    allocated_block VARCHAR(100),
    status VARCHAR(20) NOT NULL DEFAULT 'Checked-In'
        CHECK (status IN ('Checked-In', 'Treated', 'Discharged'))
);

CREATE TABLE IF NOT EXISTS resource_requests (
    resource_request_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    shelter_id VARCHAR(40) NOT NULL REFERENCES shelters(shelter_id) ON DELETE CASCADE,
    resource_name VARCHAR(120) NOT NULL,
    quantity NUMERIC(12,2) NOT NULL CHECK (quantity > 0),
    request_status VARCHAR(20) NOT NULL DEFAULT 'pending'
        CHECK (request_status IN ('pending', 'approved', 'rejected', 'fulfilled')),
    requested_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS volunteers (
    volunteer_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(120) NOT NULL,
    phone VARCHAR(25),
    email VARCHAR(180),
    skills TEXT,
    location VARCHAR(200),
    availability_status VARCHAR(20) NOT NULL DEFAULT 'available'
        CHECK (availability_status IN ('available', 'assigned', 'unavailable')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS roads (
    road_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    from_location VARCHAR(200) NOT NULL,
    to_location VARCHAR(200) NOT NULL,
    distance_km NUMERIC(10,2) NOT NULL CHECK (distance_km >= 0),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    CHECK (from_location <> to_location),
    UNIQUE (from_location, to_location)
);

CREATE TABLE IF NOT EXISTS emergency_contacts (
    contact_id VARCHAR(40) PRIMARY KEY,
    agency VARCHAR(180) NOT NULL,
    category VARCHAR(120) NOT NULL,
    phone VARCHAR(25) NOT NULL,
    alternate_phone VARCHAR(25),
    location VARCHAR(200) NOT NULL,
    badge VARCHAR(40) NOT NULL,
    description TEXT
);

CREATE TABLE IF NOT EXISTS preset_locations (
    location_id VARCHAR(60) PRIMARY KEY,
    location_name VARCHAR(180) NOT NULL,
    latitude NUMERIC(9,6) NOT NULL,
    longitude NUMERIC(9,6) NOT NULL,
    zone_type VARCHAR(120) NOT NULL
);

CREATE TABLE IF NOT EXISTS ngo_bases (
    base_id VARCHAR(60) PRIMARY KEY,
    base_name VARCHAR(160) NOT NULL,
    short_label VARCHAR(180) NOT NULL,
    location_area VARCHAR(200) NOT NULL,
    latitude NUMERIC(9,6) NOT NULL,
    longitude NUMERIC(9,6) NOT NULL,
    role_description TEXT
);

CREATE TABLE IF NOT EXISTS disaster_scenarios (
    scenario_key VARCHAR(60) PRIMARY KEY,
    label VARCHAR(160) NOT NULL,
    hazard_name VARCHAR(200) NOT NULL,
    severity VARCHAR(30) NOT NULL CHECK (severity IN ('RED ALERT', 'ORANGE ADVISORY')),
    center_latitude NUMERIC(9,6) NOT NULL,
    center_longitude NUMERIC(9,6) NOT NULL,
    radius_meters INTEGER NOT NULL CHECK (radius_meters > 0),
    affected_zones TEXT[] NOT NULL DEFAULT '{}',
    description TEXT,
    river_basin VARCHAR(160)
);

CREATE TABLE IF NOT EXISTS audit_logs (
    log_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES app_users(user_id) ON DELETE SET NULL,
    action VARCHAR(100) NOT NULL,
    entity_type VARCHAR(80) NOT NULL,
    entity_id VARCHAR(80),
    details JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_emergency_status_priority
    ON emergency_requests(request_status, priority_score DESC);
CREATE INDEX IF NOT EXISTS idx_emergency_reported_at
    ON emergency_requests(reported_at DESC);
CREATE INDEX IF NOT EXISTS idx_evacuee_shelter_status
    ON evacuee_logs(shelter_id, status);
CREATE INDEX IF NOT EXISTS idx_shelter_resource_shelter
    ON shelter_resources(shelter_id);
CREATE INDEX IF NOT EXISTS idx_resource_request_status
    ON resource_requests(request_status);
CREATE INDEX IF NOT EXISTS idx_victim_name
    ON victims(full_name);
CREATE INDEX IF NOT EXISTS idx_volunteer_status
    ON volunteers(availability_status);

CREATE OR REPLACE VIEW v_shelter_capacity AS
SELECT shelter_id, shelter_name, location_area, total_capacity, current_occupancy,
       total_capacity - current_occupancy AS available_space,
       CASE WHEN total_capacity = 0 THEN 0
            ELSE ROUND(current_occupancy::NUMERIC * 100 / total_capacity, 2)
       END AS occupancy_percent, status
FROM shelters;

CREATE OR REPLACE VIEW v_emergency_overview AS
SELECT request_id, citizen_name, location_name, category, priority, priority_score,
       people_count, request_status, reported_at, acquired_by
FROM emergency_requests;

CREATE OR REPLACE VIEW v_shelter_resource_overview AS
SELECT s.shelter_id, s.shelter_name, r.resource_name, r.current_quantity,
       r.initial_quantity, r.updated_at
FROM shelters s
JOIN shelter_resources r ON r.shelter_id = s.shelter_id;
